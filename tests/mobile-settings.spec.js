test('mobile Settings enters and exits fullscreen for the whole app', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`${origin}/settings`)
  const fullscreen = page.getByRole('button', { name: 'Mode Layar Penuh: Nonaktif. Masuk ke Layar Penuh' })
  await expect(fullscreen).toBeVisible()
  await expect(page.getByText('Fitur ini mungkin tidak didukung di semua perangkat.')).toBeVisible()
  await fullscreen.click()
  await expect.poll(() => page.evaluate(() => document.fullscreenElement === document.documentElement)).toBe(true)
  const exit = page.getByRole('button', { name: 'Mode Layar Penuh: Aktif. Keluar dari Layar Penuh' })
  await expect(exit).toBeVisible()
  await exit.click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(false)

  await page.goto(`${origin}/tas/lesson/axis-grid`)
  await expect(page.locator('.mobile-fullscreen-toggle')).toHaveCount(0)
})

test.describe('fullscreen navigation on phones', () => {
  test.use({ isMobile: true, hasTouch: true })

  test('fullscreen survives page navigation and history, and paints the selected theme', async ({ page }, testInfo) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(`${origin}/settings`)
    await page.getByRole('button', { name: 'Mode Layar Penuh: Nonaktif. Masuk ke Layar Penuh' }).click()
    const assertFullscreen = () => expect.poll(() => page.evaluate(() => document.fullscreenElement === document.documentElement)).toBe(true)
    const assertBackground = async (color) => {
      for (const selector of ['html', 'body', '#root', '.app-shell']) await expect(page.locator(selector)).toHaveCSS('background-color', color)
      await expect.poll(() => page.evaluate(() => getComputedStyle(document.documentElement, '::backdrop').backgroundColor)).toBe(color)
    }
    await assertFullscreen()
    await assertBackground('rgb(245, 247, 251)')
    await page.screenshot({ path: testInfo.outputPath('fullscreen-light.png') })
    let documentRequests = 0
    page.on('request', request => { if (request.isNavigationRequest() && request.frame() === page.mainFrame()) documentRequests += 1 })
    for (const route of ['/', '/exercises', '/exercises/score', '/settings']) {
      await page.locator(`.mobile-bottom-nav a[href="${route}"]`).click()
      await expect(page).toHaveURL(`${origin}${route}`)
      await assertFullscreen()
      await assertBackground('rgb(245, 247, 251)')
    }
    await page.goBack()
    await expect(page).toHaveURL(`${origin}/exercises/score`)
    await assertFullscreen()
    await page.goForward()
    await expect(page).toHaveURL(`${origin}/settings`)
    await assertFullscreen()
    await page.getByRole('button', { name: 'Tampilan: Mode Terang' }).click()
    await page.getByRole('radio', { name: 'Mode Malam', exact: true }).check()
    await assertBackground('rgb(14, 23, 38)')
    await page.getByRole('button', { name: 'Kembali ke Pengaturan' }).click()
    await page.getByRole('button', { name: 'Tampilan: Mode Malam' }).click()
    await page.getByRole('radio', { name: 'Mode Terang', exact: true }).check()
    await assertBackground('rgb(245, 247, 251)')
    await page.getByRole('button', { name: 'Kembali ke Pengaturan' }).click()
    expect(documentRequests).toBe(0)
    await page.getByRole('button', { name: 'Mode Layar Penuh: Aktif. Keluar dari Layar Penuh' }).click()
    await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(false)
    await page.locator('.mobile-bottom-nav a[href="/"]').click()
    await expect(page).toHaveURL(`${origin}/`)
    expect(documentRequests).toBe(1)
  })

  test('fullscreen stays active through all courses, lesson completion, and Presentation', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(`${origin}/settings`)
    await page.getByRole('button', { name: 'Mode Layar Penuh: Nonaktif. Masuk ke Layar Penuh' }).click()
    const assertFullscreen = () => expect.poll(() => page.evaluate(() => document.fullscreenElement === document.documentElement)).toBe(true)
    await page.locator('.mobile-bottom-nav a[href="/"]').click()
    for (const product of ['tas', 'trb', 'tme']) {
      await page.locator(`.hub-course-card .primary-button[href="/${product}"]`).click()
      await expect(page).toHaveURL(`${origin}/${product}/`)
      await assertFullscreen()
      const lesson = product === 'tas' ? page.locator('.course-lesson[href="/tas/lesson/axis-grid"]') : page.locator('.course-lesson').first()
      const lessonId = (await lesson.getAttribute('href')).split('/').at(-1)
      await lesson.click()
      await assertFullscreen()
      await expect(page.locator('.mobile-bottom-nav')).toBeVisible()
      const checks = page.locator('.completion-card__checks input')
      for (const check of await checks.all()) await check.check()
      await page.locator('.complete-button').click()
      await expect(page.locator('.completion-success')).toBeVisible()
      await expect.poll(() => page.evaluate(product => JSON.parse(localStorage.getItem(`cubicost:tutorial:${product}:progress`)).completed, product)).toContain(lessonId)
      await page.locator('.completion-success a').click()
      await expect(page.locator('.mobile-action-navigation strong')).toHaveText(/^1 dari /)
      await assertFullscreen()
      await page.locator('.mobile-header__back').click()
      await expect(page).toHaveURL(`${origin}/${product}/`)
      await assertFullscreen()
      await page.locator('.mobile-header__logo').click()
      await expect(page).toHaveURL(`${origin}/`)
    }
    await page.locator('.hub-tools a[href="/present"]').click()
    await expect(page.locator('.presentation-home')).toBeVisible()
    await assertFullscreen()
    await page.getByRole('button', { name: 'Mulai presentasi TAS', exact: true }).click()
    await expect(page.locator('.presentation-stage--lesson')).toBeVisible()
    await assertFullscreen()
    await page.locator('.presentation-brand').click()
    await expect(page).toHaveURL(`${origin}/`)
    await assertFullscreen()
    await page.locator('.mobile-bottom-nav a[href="/settings"]').click()
    await page.getByRole('button', { name: 'Mode Layar Penuh: Aktif. Keluar dari Layar Penuh' }).click()
    await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(false)
  })
})
